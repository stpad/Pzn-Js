let hari = "Rabu";
switch (hari) {
    case "Senin":
        console.log("Awal Minggu");
        break;
    case "Rabu":
        console.log("Pertengahan Minggu");
        break;
    case "Jumat":
        console.log("Akhir Minggu");
        break;
    default:
        console.log("Hari tidak dikenali");
}
