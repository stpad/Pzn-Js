let buah = ["apel", "jeruk", "mangga"];
let pilihan = 1;
switch (pilihan) {
    case 0:
        console.log(`Buah yang dipilih: ${buah[0]}`);
        break;
    case 1:
        console.log(`Buah yang dipilih: ${buah[1]}`);
        break;
    case 2:
        console.log(`Buah yang dipilih: ${buah[2]}`);
        break;
    default:
        console.log("Pilihan tidak tersedia");
}